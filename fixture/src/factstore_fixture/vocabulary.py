"""The draft vocabulary the loader registers: what build plan M3 turns into the core/ and
ecom-ops packages, plus the source-system identifiers the catalogue would register.

Where the kernel's near-match check flags two attributes that really are different, the
later one lists the earlier in distinct_from. Those pairs are a measure of how much
friction registration adds.
"""


def a(ident, type_, cardinality="one", doc="", unique="none"):
    return {"ident": ident, "type": type_, "cardinality": cardinality, "doc": doc, "unique": unique,
            "distinct_from": DISTINCT_FROM.get(ident, [])}


